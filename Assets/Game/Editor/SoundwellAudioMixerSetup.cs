using System;
using System.Linq;
using System.Reflection;
using UnityEditor;
using UnityEngine;
using UnityEngine.Audio;

namespace Rpg.Editor
{
    /// <summary>
    /// M6. Let the pinned Unity Editor author its own .mixer YAML; never
    /// hand-serialize native mixer data. Verify only reads saved content.
    /// The original ORK/Makinom assets and settings are unaffected.
    /// </summary>
    public static class SoundwellAudioMixerSetup
    {
        private const string Folder = "Assets/Game/Resources/Soundwell/Audio";
        private const string MixerPath = Folder + "/SoundwellMixer.mixer";
        private const string Parameter = "SoundwellSFXVolume";
        private const BindingFlags Flags =
            BindingFlags.Public | BindingFlags.NonPublic |
            BindingFlags.Instance | BindingFlags.Static;

        public static void Prepare()
        {
            AudioMixer existing = AssetDatabase.LoadAssetAtPath<AudioMixer>(MixerPath);
            if (existing != null)
            {
                Validate();
                return;
            }
            if (AssetDatabase.IsValidFolder(Folder))
                throw new InvalidOperationException("Partial M6 audio assets found; refusing to replace them.");
            if (!AssetDatabase.IsValidFolder("Assets/Game/Resources/Soundwell"))
                throw new InvalidOperationException("Soundwell Resources folder is missing.");

            AssetDatabase.CreateFolder("Assets/Game/Resources/Soundwell", "Audio");
            Type controllerType = FindEditorType("UnityEditor.Audio.AudioMixerController");
            object mixerController = Invoke(controllerType, null, "CreateMixerControllerAtPath", MixerPath);
            if (!(mixerController is AudioMixer mixer))
                throw new InvalidOperationException("Unity did not create a native AudioMixer.");
            object master = GetProperty(controllerType, mixerController, "masterGroup");
            object sfx = null;
            foreach (string name in new[] { "Music", "Ambient", "SFX" })
            {
                object group = Invoke(controllerType, mixerController, "CreateNewGroup", name, false);
                Invoke(controllerType, mixerController, "AddChildToParent", group, master);
                if (name == "SFX")
                    sfx = group;
            }

            Type groupType = sfx.GetType();
            object volumeGuid = Invoke(groupType, sfx, "GetGUIDForVolume");
            Type pathType = FindEditorType("UnityEditor.Audio.AudioGroupParameterPath");
            object volumePath = Activator.CreateInstance(pathType, Flags, null,
                new[] { sfx, volumeGuid }, null);
            Invoke(controllerType, mixerController, "AddExposedParameter", volumePath);

            // Unity's editor chooses an autogenerated parameter name. Give the
            // exposed SFX attenuation a stable game-owned name for runtime APIs.
            PropertyInfo exposed = controllerType.GetProperty("exposedParameters", Flags);
            if (exposed == null || !exposed.CanWrite)
                throw new InvalidOperationException("Unity AudioMixer does not expose editor parameter metadata.");
            var values = (Array)exposed.GetValue(mixerController);
            if (values == null || values.Length != 1)
                throw new InvalidOperationException("M6 requires exactly one exposed mixer volume.");
            object parameter = values.GetValue(0);
            FieldInfo nameField = parameter.GetType().GetField("name", Flags);
            if (nameField == null)
                throw new InvalidOperationException("Unity AudioMixer exposed parameter name is unavailable.");
            nameField.SetValue(parameter, Parameter);
            values.SetValue(parameter, 0);
            exposed.SetValue(mixerController, values);
            EditorUtility.SetDirty((UnityEngine.Object)mixerController);
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh(ImportAssetOptions.ForceUpdate);
            Validate();
        }

        public static void Validate()
        {
            var mixer = AssetDatabase.LoadAssetAtPath<AudioMixer>(MixerPath);
            if (mixer == null)
                throw new InvalidOperationException("The saved M6 native AudioMixer is missing.");
            var groups = mixer.FindMatchingGroups("");
            if (groups.Length != 4 ||
                groups.Count(g => g.name == "Master") != 1 ||
                groups.Count(g => g.name == "Music") != 1 ||
                groups.Count(g => g.name == "Ambient") != 1 ||
                groups.Count(g => g.name == "SFX") != 1)
                throw new InvalidOperationException("M6 must have only Master/Music/Ambient/SFX buses.");
            if (mixer.FindSnapshot("Snapshot") == null)
                throw new InvalidOperationException("The native mixer must have a saved starting snapshot.");

            Type editorType = FindEditorType("UnityEditor.Audio.AudioMixerController");
            var controller = (object)mixer;
            PropertyInfo exposed = editorType.GetProperty("exposedParameters", Flags);
            var values = exposed != null ? exposed.GetValue(controller) as Array : null;
            if (values == null || values.Length != 1 ||
                (string)values.GetValue(0).GetType().GetField("name", Flags)?.GetValue(values.GetValue(0)) != Parameter)
                throw new InvalidOperationException("The SFX attenuation must expose one stable volume parameter.");

            Debug.Log("RPG_SOUNDWELL_AUDIO_MIXER_VALIDATED");
        }

        private static Type FindEditorType(string fullName)
        {
            Type found = AppDomain.CurrentDomain.GetAssemblies()
                .Select(a => a.GetType(fullName, false)).FirstOrDefault(t => t != null);
            if (found != null)
                return found;
            foreach (string name in new[] { "UnityEditor.AudioModule", "UnityEditor" })
            {
                try
                {
                    found = Assembly.Load(name).GetType(fullName, false);
                    if (found != null)
                        return found;
                }
                catch (System.IO.FileNotFoundException) { }
            }
            throw new InvalidOperationException("Pinned Unity Editor lacks native audio type: " + fullName);
        }

        private static object GetProperty(Type type, object target, string name)
        {
            PropertyInfo property = type.GetProperty(name, Flags);
            if (property == null)
                throw new MissingMemberException(type.FullName, name);
            return property.GetValue(target);
        }

        private static object Invoke(Type type, object target, string name, params object[] args)
        {
            var candidates = type.GetMethods(Flags)
                .Where(m => m.Name == name && m.GetParameters().Length == args.Length);
            foreach (MethodInfo method in candidates)
            {
                var parameters = method.GetParameters();
                if (parameters.Where((p, i) => args[i] != null &&
                    !p.ParameterType.IsInstanceOfType(args[i])).Any())
                    continue;
                try { return method.Invoke(target, args); }
                catch (TargetInvocationException ex) when (ex.InnerException != null)
                {
                    throw ex.InnerException;
                }
            }
            throw new MissingMethodException(type.FullName, name);
        }
    }
}
